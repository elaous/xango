package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/elaous/gojiberry/internal/transpile"
	"github.com/elaous/gojiberry/internal/transpile/experimental"
)

func main() {
	experimentalFlag := flag.Bool("experimental", os.Getenv("XANGO_EXPERIMENTAL") == "1", "enable experimental resource imports (.hcl/.proto/.capnp/.sql, JSON .(TypeName) inference); also read from XANGO_EXPERIMENTAL=1")
	flag.Parse()

	opts := transpile.Options{}
	if *experimentalFlag {
		opts.Experimental = true
		opts.ExperimentalLoaders = experimental.Loaders()
	}

	dirs := flag.Args()
	if len(dirs) == 0 {
		dirs = []string{"."}
	}

	var failed bool
	for _, dir := range dirs {
		err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				// "experimental" dirs need -experimental: else skipped
				if d.Name() == "experimental" && !opts.Experimental {
					return filepath.SkipDir
				}
				return nil
			}
			if !strings.HasSuffix(path, ".xg") {
				return nil
			}
			if genErr := generate(path, opts); genErr != nil {
				fmt.Fprintf(os.Stderr, "xgc: %v\n", genErr)
				failed = true
			}
			return nil
		})
		if err != nil {
			fmt.Fprintf(os.Stderr, "xgc: %v\n", err)
			failed = true
		}
	}
	if failed {
		os.Exit(1)
	}
}

func generate(path string, opts transpile.Options) error {
	src, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("reading %s: %w", path, err)
	}

	generated, err := transpile.TranspileWithOptions(path, src, opts)
	if err != nil {
		return fmt.Errorf("transpiling %s: %w", path, err)
	}

	header := fmt.Sprintf("// Code generated by xgc from %s. DO NOT EDIT.\n\n", filepath.Base(path))
	full := header + string(generated)

	formatted, err := format.Source([]byte(full))
	if err != nil {
		return fmt.Errorf("%s: generated invalid Go source: %w\n---\n%s", path, err, full)
	}

	outPath := strings.TrimSuffix(path, ".xg") + ".xg.go"
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", outPath, err)
	}
	fmt.Printf("xgc: %s -> %s\n", path, outPath)
	return nil
}
