// Command goxc transpiles .gox files into gofmt-clean .go files.
//
// Usage:
//
//	goxc [dirs...]
//
// Every path/to/name.gox becomes path/to/name.gox.go in the same
// directory and package. Defaults to "." if no directories are given.
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/elaous/gojiberry/internal/transpile"
)

func main() {
	dirs := os.Args[1:]
	if len(dirs) == 0 {
		dirs = []string{"."}
	}

	var failed bool
	for _, dir := range dirs {
		err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() || !strings.HasSuffix(path, ".gox") {
				return nil
			}
			if genErr := generate(path); genErr != nil {
				fmt.Fprintf(os.Stderr, "goxc: %v\n", genErr)
				failed = true
			}
			return nil
		})
		if err != nil {
			fmt.Fprintf(os.Stderr, "goxc: %v\n", err)
			failed = true
		}
	}
	if failed {
		os.Exit(1)
	}
}

func generate(path string) error {
	src, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("reading %s: %w", path, err)
	}

	generated, err := transpile.Transpile(path, src)
	if err != nil {
		return fmt.Errorf("transpiling %s: %w", path, err)
	}

	header := fmt.Sprintf("// Code generated by goxc from %s. DO NOT EDIT.\n\n", filepath.Base(path))
	full := header + string(generated)

	formatted, err := format.Source([]byte(full))
	if err != nil {
		return fmt.Errorf("%s: generated invalid Go source: %w\n---\n%s", path, err, full)
	}

	outPath := strings.TrimSuffix(path, ".gox") + ".gox.go"
	if err := os.WriteFile(outPath, formatted, 0o644); err != nil {
		return fmt.Errorf("writing %s: %w", outPath, err)
	}
	fmt.Printf("goxc: %s -> %s\n", path, outPath)
	return nil
}
