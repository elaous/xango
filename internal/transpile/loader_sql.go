package transpile

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"strings"
)

// sqlVarAnnotationRe matches a `-- @var: Name` line, gox's SQL import
// convention: everything between one annotation and the next (or EOF)
// becomes that name's query text.
var sqlVarAnnotationRe = regexp.MustCompile(`^\s*--\s*@var:\s*([A-Za-z_][A-Za-z0-9_]*)\s*$`)

// loadSQL splits a .sql file into named queries via `-- @var: Name`
// annotations and generates a Go subpackage of string constants, one
// per annotation, under internal/goxgen/sql/<alias>/ -- the same
// generated-subpackage pattern as HCL, since a single .sql file
// commonly names several queries and each needs its own identifier
// rather than the whole file collapsing to one bound value the way
// CSS/JSON do.
//
//	-- @var: SelectFromBlob
//	SELECT * FROM blob;
//
// generates (package <alias>):
//
//	var SelectFromBlob = "SELECT * FROM blob"
//
// A trailing semicolon and surrounding whitespace on each query are
// trimmed. Content before the first annotation is ignored (so a file
// can open with an ordinary, non-bound comment banner).
func loadSQL(in loaderInput) (loaderResult, error) {
	abs, err := resolveResourcePath(in)
	if err != nil {
		return loaderResult{}, err
	}
	data, err := os.ReadFile(abs)
	if err != nil {
		return loaderResult{}, fmt.Errorf("gox: SQL import %q: %w", in.Path, err)
	}

	queries, err := parseSQLVars(string(data))
	if err != nil {
		return loaderResult{}, fmt.Errorf("gox: SQL import %q: %w", in.Path, err)
	}
	if len(queries) == 0 {
		return loaderResult{}, fmt.Errorf("gox: SQL import %q: no `-- @var: Name` annotations found", in.Path)
	}

	moduleRoot, modulePath, err := findModuleRoot(in.BaseDir)
	if err != nil {
		return loaderResult{}, fmt.Errorf("gox: SQL import %q: %w", in.Path, err)
	}
	pkgDir := filepath.Join(moduleRoot, "internal", "goxgen", "sql", in.Alias)
	if err := os.MkdirAll(pkgDir, 0o755); err != nil {
		return loaderResult{}, fmt.Errorf("gox: SQL import %q: %w", in.Path, err)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by goxc from a gox SQL import. DO NOT EDIT.\npackage %s\n\nvar (\n", in.Alias)
	for _, q := range queries {
		fmt.Fprintf(&b, "\t%s = %s\n", q.name, goQuotedSQL(q.text))
	}
	b.WriteString(")\n")

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return loaderResult{}, fmt.Errorf("gox: generated queries for %q are not valid Go: %w", in.Path, err)
	}
	if err := os.WriteFile(filepath.Join(pkgDir, "queries.go"), formatted, 0o644); err != nil {
		return loaderResult{}, fmt.Errorf("gox: writing generated queries for %q: %w", in.Path, err)
	}

	return loaderResult{ImportPath: modulePath + "/internal/goxgen/sql/" + in.Alias}, nil
}

type sqlNamedQuery struct {
	name string
	text string
}

func parseSQLVars(src string) ([]sqlNamedQuery, error) {
	var queries []sqlNamedQuery
	var currentName string
	var currentLines []string
	flush := func() {
		if currentName != "" {
			text := strings.TrimSpace(strings.Join(currentLines, "\n"))
			text = strings.TrimSuffix(text, ";")
			text = strings.TrimSpace(text)
			queries = append(queries, sqlNamedQuery{name: currentName, text: text})
		}
	}
	for _, line := range strings.Split(src, "\n") {
		if m := sqlVarAnnotationRe.FindStringSubmatch(line); m != nil {
			flush()
			currentName = m[1]
			currentLines = nil
			continue
		}
		if currentName != "" {
			currentLines = append(currentLines, line)
		}
	}
	flush()

	seen := map[string]bool{}
	for _, q := range queries {
		if seen[q.name] {
			return nil, fmt.Errorf("duplicate @var name %q", q.name)
		}
		seen[q.name] = true
	}
	return queries, nil
}

// goQuotedSQL prefers a backtick raw string (keeps a multi-line query
// readable in the generated file) and falls back to a normal quoted
// string when the content itself contains a backtick.
func goQuotedSQL(s string) string {
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}
