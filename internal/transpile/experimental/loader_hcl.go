// hclSchema is xango's schema DSL:
//
//	table "users" {
//	  column "id"    { type = "uuid"   primary_key = true }
//	  column "email" { type = "string" unique = true }
//	}
//
// Not general-purpose HCL -- a small, fixed schema shape decoded via
// hclsimple, real HCL syntax (comments, references, etc. all work; the
// block/attribute shape is just narrow by design).
type hclSchema struct {
	Tables []hclTable `hcl:"table,block"`
}

type hclTable struct {
	Name    string      `hcl:"name,label"`
	Columns []hclColumn `hcl:"column,block"`
}

type hclColumn struct {
	Name       string  `hcl:"name,label"`
	Type       string  `hcl:"type"`
	PrimaryKey bool    `hcl:"primary_key,optional"`
	NotNull    bool    `hcl:"not_null,optional"`
	Unique     bool    `hcl:"unique,optional"`
	References *string `hcl:"references,optional"` // "othertable.column"
}

// hclTypeMap maps a schema column type to a Go field type and a SQL
// column type. Unrecognized types fall back to Go `any` / SQL TEXT.
var hclTypeMap = map[string][2]string{
	"uuid":      {"string", "UUID"},
	"string":    {"string", "TEXT"},
	"text":      {"string", "TEXT"},
	"int":       {"int", "INTEGER"},
	"integer":   {"int", "INTEGER"},
	"bigint":    {"int64", "BIGINT"},
	"float":     {"float64", "DOUBLE PRECISION"},
	"double":    {"float64", "DOUBLE PRECISION"},
	"bool":      {"bool", "BOOLEAN"},
	"boolean":   {"bool", "BOOLEAN"},
	"timestamp": {"time.Time", "TIMESTAMP"},
	"date":      {"time.Time", "DATE"},
}

// loadHCL parses an xango schema file and generates a Go package (model
// structs) plus a SQL migration file, both written under
// <moduleRoot>/internal/xggen/hcl/<alias>/, then rewrites the import
// to point at the generated package -- so `schema.Users{}` works like
// any other imported type, which a value spliced into the importing
// file (as JSON/CSS do) couldn't give since Go has no runtime notion of
// a type namespace.
//
// Scoped to snapshot generation: each run overwrites the models file
// and (0001_init.sql) from the current schema, there's no diffing
// against a previous schema version to produce an incremental
// migration.
func LoadHCL(in transpile.LoaderInput) (transpile.LoaderResult, error) {
	abs, err := transpile.ResolveResourcePath(in)
	if err != nil {
		return transpile.LoaderResult{}, err
	}
	var schema hclSchema
	if err := hclsimple.DecodeFile(abs, nil, &schema); err != nil {
		return transpile.LoaderResult{}, fmt.Errorf("xango: HCL import %q: %w", in.Path, err)
	}

	moduleRoot, modulePath, err := transpile.FindModuleRoot(in.BaseDir)
	if err != nil {
		return transpile.LoaderResult{}, fmt.Errorf("xango: HCL import %q: %w", in.Path, err)
	}

	pkgDir := filepath.Join(moduleRoot, "internal", "xggen", "hcl", in.Alias)
	if err := os.MkdirAll(pkgDir, 0o755); err != nil {
		return transpile.LoaderResult{}, fmt.Errorf("xango: HCL import %q: %w", in.Path, err)
	}
	if err := claimAlias(pkgDir, abs); err != nil {
		return transpile.LoaderResult{}, fmt.Errorf("xango: HCL import %q: %w", in.Path, err)
	}

	modelsSrc, _ := generateHCLModels(in.Alias, schema)
	formatted, err := format.Source([]byte(modelsSrc))
	if err != nil {
		return transpile.LoaderResult{}, fmt.Errorf("xango: generated models for %q are not valid Go: %w", in.Path, err)
	}
	if err := os.WriteFile(filepath.Join(pkgDir, "models.go"), formatted, 0o644); err != nil {
		return transpile.LoaderResult{}, fmt.Errorf("xango: writing generated models for %q: %w", in.Path, err)
	}

	migrationsDir := filepath.Join(pkgDir, "migrations")
	if err := os.MkdirAll(migrationsDir, 0o755); err != nil {
		return transpile.LoaderResult{}, fmt.Errorf("xango: HCL import %q: %w", in.Path, err)
	}
	sql, err := generateHCLMigration(schema)
	if err != nil {
		return transpile.LoaderResult{}, fmt.Errorf("xango: HCL import %q: %w", in.Path, err)
	}
	if err := os.WriteFile(filepath.Join(migrationsDir, "0001_init.sql"), []byte(sql), 0o644); err != nil {
		return transpile.LoaderResult{}, fmt.Errorf("xango: writing generated migration for %q: %w", in.Path, err)
	}

	importPath := modulePath + "/internal/xggen/hcl/" + in.Alias
	return transpile.LoaderResult{ImportPath: importPath}, nil
}

func goFieldType(colType string) string {
	if m, ok := hclTypeMap[strings.ToLower(colType)]; ok {
		return m[0]
	}
	return "any"
}

func sqlColType(colType string) string {
	if m, ok := hclTypeMap[strings.ToLower(colType)]; ok {
		return m[1]
	}
	return "TEXT"
}

func generateHCLModels(pkgName string, schema hclSchema) (string, bool) {
	usesTime := false
	for _, t := range schema.Tables {
		for _, c := range t.Columns {
			if goFieldType(c.Type) == "time.Time" {
				usesTime = true
			}
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by xgc from an xango HCL schema import. DO NOT EDIT.\npackage %s\n\n", pkgName)
	if usesTime {
		b.WriteString("import \"time\"\n\n")
	}
	for _, t := range schema.Tables {
		fmt.Fprintf(&b, "type %s struct {\n", transpile.CapWords(t.Name))
		for _, c := range t.Columns {
			ft := goFieldType(c.Type)
			tag := fmt.Sprintf("`db:%s`", strconv.Quote(c.Name))
			fmt.Fprintf(&b, "\t%s %s %s\n", transpile.CapWords(c.Name), ft, tag)
		}
		b.WriteString("}\n\n")
	}
	return b.String(), usesTime
}

func generateHCLMigration(schema hclSchema) (string, error) {
	var b strings.Builder
	b.WriteString("-- Code generated by xgc from an xango HCL schema import. DO NOT EDIT.\n")
	b.WriteString("-- Snapshot of the current schema; this is not a diff against a previous version.\n\n")
	for _, t := range orderTables(schema.Tables) {
		fmt.Fprintf(&b, "CREATE TABLE IF NOT EXISTS %s (\n", quoteIdent(t.Name))
		var lines []string
		for _, c := range t.Columns {
			line := fmt.Sprintf("  %s %s", quoteIdent(c.Name), sqlColType(c.Type))
			if c.PrimaryKey {
				line += " PRIMARY KEY"
			}
			if c.NotNull {
				line += " NOT NULL"
			}
			if c.Unique {
				line += " UNIQUE"
			}
			if c.References != nil {
				refTable, refCol, ok := strings.Cut(*c.References, ".")
				if !ok || refTable == "" || refCol == "" {
					return "", fmt.Errorf("column %s.%s: references %q must be table.column", t.Name, c.Name, *c.References)
				}
				line += fmt.Sprintf(" REFERENCES %s(%s)", quoteIdent(refTable), quoteIdent(refCol))
			}
			lines = append(lines, line)
		}
		b.WriteString(strings.Join(lines, ",\n"))
		b.WriteString("\n);\n\n")
	}
	return b.String(), nil
}

// quoteIdent quotes an SQL identifier, so a reserved word, a hyphen or a
// space in a table or column name stays one name.
func quoteIdent(s string) string { return `"` + strings.ReplaceAll(s, `"`, `""`) + `"` }

// orderTables lists tables so that one a column references comes before the
// table that references it (the CREATE TABLEs would otherwise fail on a
// forward reference); other tables keep their file order, and so does a
// reference cycle.
func orderTables(tables []hclTable) []hclTable {
	byName := map[string]int{}
	for i, t := range tables {
		byName[t.Name] = i
	}
	state := make([]int, len(tables)) // 0 new, 1 visiting, 2 done
	var out []hclTable
	var visit func(i int)
	visit = func(i int) {
		if state[i] != 0 {
			return
		}
		state[i] = 1
		for _, c := range tables[i].Columns {
			if c.References == nil {
				continue
			}
			if refTable, _, ok := strings.Cut(*c.References, "."); ok {
				if j, found := byName[refTable]; found && j != i {
					visit(j)
				}
			}
		}
		state[i] = 2
		out = append(out, tables[i])
	}
	for i := range tables {
		visit(i)
	}
	return out
}

// claimAlias records which schema file owns the generated package in dir, and
// refuses a second, different file under the same alias: its output would
// silently overwrite the first's.
func claimAlias(dir, source string) error {
	marker := filepath.Join(dir, ".source")
	if prev, err := os.ReadFile(marker); err == nil && strings.TrimSpace(string(prev)) != source {
		return fmt.Errorf("the alias is already used for %s; give this import another alias", strings.TrimSpace(string(prev)))
	}
	return os.WriteFile(marker, []byte(source+"\n"), 0o644)
}
