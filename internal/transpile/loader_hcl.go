package transpile

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"strings"

	"github.com/hashicorp/hcl/v2/hclsimple"
)

// hclSchema is gox's schema DSL:
//
//	table "users" {
//	  column "id"    { type = "uuid"   primary_key = true }
//	  column "email" { type = "string" unique = true }
//	}
//
// Not general-purpose HCL -- a small, fixed schema shape decoded via
// hclsimple, real HCL syntax (comments, references, etc. all work; the
// block/attribute shape is just narrow by design).
type hclSchema struct {
	Tables []hclTable `hcl:"table,block"`
}

type hclTable struct {
	Name    string      `hcl:"name,label"`
	Columns []hclColumn `hcl:"column,block"`
}

type hclColumn struct {
	Name       string  `hcl:"name,label"`
	Type       string  `hcl:"type"`
	PrimaryKey bool    `hcl:"primary_key,optional"`
	NotNull    bool    `hcl:"not_null,optional"`
	Unique     bool    `hcl:"unique,optional"`
	References *string `hcl:"references,optional"` // "othertable.column"
}

// hclTypeMap maps a schema column type to a Go field type and a SQL
// column type. Unrecognized types fall back to Go `any` / SQL TEXT.
var hclTypeMap = map[string][2]string{
	"uuid":      {"string", "UUID"},
	"string":    {"string", "TEXT"},
	"text":      {"string", "TEXT"},
	"int":       {"int", "INTEGER"},
	"integer":   {"int", "INTEGER"},
	"bigint":    {"int64", "BIGINT"},
	"float":     {"float64", "DOUBLE PRECISION"},
	"double":    {"float64", "DOUBLE PRECISION"},
	"bool":      {"bool", "BOOLEAN"},
	"boolean":   {"bool", "BOOLEAN"},
	"timestamp": {"time.Time", "TIMESTAMP"},
	"date":      {"time.Time", "DATE"},
}

// loadHCL parses a gox schema file and generates a Go package (model
// structs) plus a SQL migration file, both written under
// <moduleRoot>/internal/goxgen/hcl/<alias>/, then rewrites the import
// to point at the generated package -- so `schema.Users{}` works like
// any other imported type, which a value spliced into the importing
// file (as JSON/CSS do) couldn't give since Go has no runtime notion of
// a type namespace.
//
// Scoped to snapshot generation: each run overwrites the models file
// and (0001_init.sql) from the current schema, there's no diffing
// against a previous schema version to produce an incremental
// migration.
func loadHCL(in loaderInput) (loaderResult, error) {
	abs, err := resolveResourcePath(in)
	if err != nil {
		return loaderResult{}, err
	}
	var schema hclSchema
	if err := hclsimple.DecodeFile(abs, nil, &schema); err != nil {
		return loaderResult{}, fmt.Errorf("gox: HCL import %q: %w", in.Path, err)
	}

	moduleRoot, modulePath, err := findModuleRoot(in.BaseDir)
	if err != nil {
		return loaderResult{}, fmt.Errorf("gox: HCL import %q: %w", in.Path, err)
	}

	pkgDir := filepath.Join(moduleRoot, "internal", "goxgen", "hcl", in.Alias)
	if err := os.MkdirAll(pkgDir, 0o755); err != nil {
		return loaderResult{}, fmt.Errorf("gox: HCL import %q: %w", in.Path, err)
	}

	modelsSrc, _ := generateHCLModels(in.Alias, schema)
	formatted, err := format.Source([]byte(modelsSrc))
	if err != nil {
		return loaderResult{}, fmt.Errorf("gox: generated models for %q are not valid Go: %w", in.Path, err)
	}
	if err := os.WriteFile(filepath.Join(pkgDir, "models.go"), formatted, 0o644); err != nil {
		return loaderResult{}, fmt.Errorf("gox: writing generated models for %q: %w", in.Path, err)
	}

	migrationsDir := filepath.Join(pkgDir, "migrations")
	if err := os.MkdirAll(migrationsDir, 0o755); err != nil {
		return loaderResult{}, fmt.Errorf("gox: HCL import %q: %w", in.Path, err)
	}
	sql := generateHCLMigration(schema)
	if err := os.WriteFile(filepath.Join(migrationsDir, "0001_init.sql"), []byte(sql), 0o644); err != nil {
		return loaderResult{}, fmt.Errorf("gox: writing generated migration for %q: %w", in.Path, err)
	}

	importPath := modulePath + "/internal/goxgen/hcl/" + in.Alias
	return loaderResult{ImportPath: importPath}, nil
}

func goFieldType(colType string) string {
	if m, ok := hclTypeMap[strings.ToLower(colType)]; ok {
		return m[0]
	}
	return "any"
}

func sqlColType(colType string) string {
	if m, ok := hclTypeMap[strings.ToLower(colType)]; ok {
		return m[1]
	}
	return "TEXT"
}

func capWords(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func generateHCLModels(pkgName string, schema hclSchema) (string, bool) {
	usesTime := false
	for _, t := range schema.Tables {
		for _, c := range t.Columns {
			if goFieldType(c.Type) == "time.Time" {
				usesTime = true
			}
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by goxc from a gox HCL schema import. DO NOT EDIT.\npackage %s\n\n", pkgName)
	if usesTime {
		b.WriteString("import \"time\"\n\n")
	}
	for _, t := range schema.Tables {
		fmt.Fprintf(&b, "type %s struct {\n", capWords(t.Name))
		for _, c := range t.Columns {
			ft := goFieldType(c.Type)
			tag := fmt.Sprintf("`db:%s`", strconv.Quote(c.Name))
			fmt.Fprintf(&b, "\t%s %s %s\n", capWords(c.Name), ft, tag)
		}
		b.WriteString("}\n\n")
	}
	return b.String(), usesTime
}

func generateHCLMigration(schema hclSchema) string {
	var b strings.Builder
	b.WriteString("-- Code generated by goxc from a gox HCL schema import. DO NOT EDIT.\n")
	b.WriteString("-- Snapshot of the current schema; this is not a diff against a previous version.\n\n")
	for _, t := range schema.Tables {
		fmt.Fprintf(&b, "CREATE TABLE IF NOT EXISTS %s (\n", t.Name)
		var lines []string
		for _, c := range t.Columns {
			line := fmt.Sprintf("  %s %s", c.Name, sqlColType(c.Type))
			if c.PrimaryKey {
				line += " PRIMARY KEY"
			}
			if c.NotNull {
				line += " NOT NULL"
			}
			if c.Unique {
				line += " UNIQUE"
			}
			if c.References != nil {
				refTable, refCol, ok := strings.Cut(*c.References, ".")
				if ok {
					line += fmt.Sprintf(" REFERENCES %s(%s)", refTable, refCol)
				}
			}
			lines = append(lines, line)
		}
		b.WriteString(strings.Join(lines, ",\n"))
		b.WriteString("\n);\n\n")
	}
	return b.String()
}
